import { randomUUID } from 'node:crypto'
import pg from 'pg'

const { Pool } = pg
const BLOG_COUNT = 50
const COLLEGE_ID = 'cmuvij5jp00015j8au256obgd'
const COLLEGE_NAME = 'Stanford University'
const SEED_AUTHOR_EMAIL = 'mock-blog-author@stanford.example'
const DATABASE_URL = 'postgresql://lumina_user:lumina_password@localhost:5432/lumina_dev'

const blogs = [
  ['Building Better Study Habits', 'Education', ['study', 'productivity', 'students']],
  ['A Beginner Guide to Campus Hackathons', 'Technology', ['hackathon', 'technology', 'campus']],
  ['How to Prepare for Technical Interviews', 'Career', ['career', 'interviews', 'engineering']],
  ['Making Friends in a New College', 'Community', ['community', 'college-life', 'friends']],
  [
    'The Complete Guide to Open Source Contributions',
    'Technology',
    ['open-source', 'coding', 'community'],
  ],
  ['Managing Stress During Exam Season', 'Wellness', ['wellness', 'exams', 'mental-health']],
  ['Designing an Effective Portfolio', 'Career', ['portfolio', 'design', 'career']],
  ['Why Every Student Should Learn Git', 'Technology', ['git', 'development', 'learning']],
  ['Planning a Sustainable Campus Event', 'Campus Life', ['events', 'sustainability', 'campus']],
  ['Finding Your First Internship', 'Career', ['internships', 'career', 'students']],
]

function createBlog(index) {
  const [title, category, topics] = blogs[index % blogs.length]
  const number = index + 1

  return {
    title: `${title} - Part ${number}`,
    subtitle: `Practical ideas and lessons for students in our college community.`,
    content:
      `This is mock blog post ${number}. ${title} is an important topic for students ` +
      'who want to learn, connect with others, and make steady progress. ' +
      'Use these ideas as a starting point, share your experience, and keep improving together.',
    category,
    topics: [...topics, 'mock-blog-seed'],
    blocks: [
      {
        id: `mock-block-${number}`,
        type: 'paragraph',
        content:
          `This sample article was generated by the Lumina mock blog seed script. ` +
          `It is post ${number} of ${BLOG_COUNT}.`,
      },
    ],
  }
}

async function main() {
  const pool = new Pool({
    connectionString: 'postgresql://lumina_user:lumina_password@localhost:5432/lumina_dev',
  })
  const client = await pool.connect()

  try {
    await client.query('BEGIN')

    await client.query(
      `INSERT INTO "College"
        ("id", "name", "domain", "createdAt", "updatedAt")
       VALUES ($1, $2, $3, NOW(), NOW())
       ON CONFLICT ("id") DO UPDATE
       SET "name" = EXCLUDED."name", "updatedAt" = NOW()`,
      [COLLEGE_ID, COLLEGE_NAME, 'stanford.example']
    )

    const { rowCount: collegeAuthorCount } = await client.query(
      'SELECT 1 FROM "User" WHERE "collegeId" = $1',
      [COLLEGE_ID]
    )

    if (!collegeAuthorCount) {
      await client.query(
        `INSERT INTO "User"
          ("id", "email", "name", "collegeId", "createdAt", "updatedAt")
         VALUES ($1, $2, $3, $4, NOW(), NOW())
         ON CONFLICT ("email") DO UPDATE
         SET "name" = EXCLUDED."name", "collegeId" = EXCLUDED."collegeId",
             "updatedAt" = NOW()`,
        [randomUUID(), SEED_AUTHOR_EMAIL, 'Stanford Mock Blog Author', COLLEGE_ID]
      )
    }

    const { rows: users } = await client.query(
      'SELECT "id" FROM "User" WHERE "collegeId" = $1 ORDER BY "createdAt" ASC LIMIT 50',
      [COLLEGE_ID]
    )

    if (users.length === 0) {
      throw new Error(
        `No users found for college ${COLLEGE_ID}. Assign a user to this college first.`
      )
    }

    for (let index = 0; index < BLOG_COUNT; index += 1) {
      const blog = createBlog(index)
      const authorId = users[index % users.length].id

      await client.query(
        `INSERT INTO "Post"
          ("id", "authorId", "title", "subtitle", "content", "category", "topics", "blocks",
           "visibility", "anonymous", "isAnnouncement", "location", "createdAt", "updatedAt")
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8::jsonb, 'PUBLIC', false, false, $9, NOW(), NOW())`,
        [
          randomUUID(),
          authorId,
          blog.title,
          blog.subtitle,
          blog.content,
          blog.category,
          blog.topics,
          JSON.stringify(blog.blocks),
          'Lumina Campus',
        ]
      )
    }

    await client.query('COMMIT')
    console.log(`Seeded ${BLOG_COUNT} mock blog posts using ${users.length} existing user(s).`)
  } catch (error) {
    await client.query('ROLLBACK')
    console.error('Mock blog seeding failed:', error)
    process.exitCode = 1
  } finally {
    client.release()
    await pool.end()
  }
}

main()
